/**
 * These two tours exist because the hardest part of the first week is not any
 * single feature — it is knowing where to look. Every stop highlights one real
 * control and says what it is for, in words that assume the founder has never
 * seen the page. Nothing here presses anything: navigation stops are
 * information, and the founder moves when they want to.
 *
 * The two shells are different on purpose. Outside a business the sidebar is
 * about your account and your portfolio; inside one, the same rail becomes that
 * business's own set of pages. A founder who does not know that gets lost, so it
 * gets its own tour.
 */

